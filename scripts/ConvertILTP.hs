import Control.Monad (filterM, unless, when)
import Control.Monad.State
import Data.Char (isAlpha, isAlphaNum, isSpace, toLower)
import Data.List (findIndex, isPrefixOf, isSuffixOf, sort, stripPrefix)
import Data.Maybe (mapMaybe)
import System.Directory (createDirectoryIfMissing, doesDirectoryExist, listDirectory, removeDirectoryRecursive, doesPathExist)
import System.Environment (getArgs)
import System.Exit (die)
import System.FilePath (dropExtension, pathSeparator, splitFileName, splitPath, takeDirectory, (</>))

data Status = Theorem | NonTheorem | Unsolved deriving (Show)

data Problem = Problem
  { status :: Status,
    hypotheses :: [String],
    conjecture :: String
  }
  deriving (Show)

data Token = Atom String | Operator String | LeftParen | RightParen deriving (Show)

type Formula = [Token]

renderFormula :: Formula -> String
renderFormula formula = unwords $ map renderToken formula
  where
    renderToken (Atom "$true") = "⊤"
    renderToken (Atom "$false") = "⊥"
    renderToken (Atom name) = name
    renderToken (Operator "~") = "¬"
    renderToken (Operator "&") = "∧"
    renderToken (Operator "|") = "∨"
    renderToken (Operator "=>") = "→"
    renderToken (Operator "<=>") = "↔"
    renderToken (LeftParen) = "("
    renderToken (RightParen) = ")"
    renderToken _ = "error"

data ParsedProblem = ParsedProblem
  { parsedStatus :: Status,
    parsedHypotheses :: [Formula],
    parsedConjecture :: Formula
  }
  deriving (Show)

parseProblem :: Problem -> Either String ParsedProblem
parseProblem problem = do
  hypotheses_ <- mapM tokenizeFormula (hypotheses problem)
  conjecture_ <- tokenizeFormula (conjecture problem)
  Right $ ParsedProblem {parsedStatus = status problem, parsedHypotheses = hypotheses_, parsedConjecture = conjecture_}

data ConvertedProblem = ConvertedProblem
  { entailment :: String,
    renderedHypotheses :: [String],
    renderedConjecture :: String
  }
  deriving (Show)

renderProblem :: ParsedProblem -> Maybe ConvertedProblem
renderProblem problem =
  let convertedHypothesis = map renderFormula (parsedHypotheses problem)
   in let convertedConjecture = renderFormula (parsedConjecture problem)
       in case parsedStatus problem of
            Theorem -> Just $ ConvertedProblem {entailment = "derivable", renderedHypotheses = convertedHypothesis, renderedConjecture = convertedConjecture}
            NonTheorem -> Just $ ConvertedProblem {entailment = "underivable", renderedHypotheses = convertedHypothesis, renderedConjecture = convertedConjecture}
            Unsolved -> Nothing

renderYaml :: FilePath -> String -> ConvertedProblem -> String
renderYaml filePath caseId problem =
  unlines $
    [ "#  This file is autogenerated. Do not edit it manually",
      "id: " ++ caseId,
      "kind: sequent",
      "source: iltp",
      "tags: [iltp, external]",
      "provenance:",
      "  kind: external",
      "  name: ILTP",
      "  version: 1.1.2-propositional",
      "  original_path: " ++ filePath,
      "input:",
      "  context: []"
    ]
      ++ renderHypotheses (renderedHypotheses problem)
      ++ [ "  goal: " ++ (yamlQuote $ renderedConjecture problem),
           "expected:",
           "  entailment: " ++ (entailment problem),
           "  premises_consistency: consistent"
         ]
  where
    renderHypotheses [] = ["  hypotheses: []"]
    renderHypotheses hypotheses_ = "  hypotheses:" : map (\hypothesis -> "    - " ++ (yamlQuote hypothesis)) hypotheses_

formatCaseId :: FilePath -> String
formatCaseId file =
  let (filePath, fileName) = splitFileName file
   in let kind = map toLower (last $ splitPath $ takeDirectory filePath)
       in let name =
                concatMap
                  ( \letter -> case letter of
                      '+' -> "-plus-"
                      '.' -> "-"
                      c -> [c]
                  )
                  (map toLower (dropExtension fileName))
           in kind ++ "." ++ name

isAtomStart :: Char -> Bool
isAtomStart c = isAlpha c || c == '$' || c == '_'

isAtomChar :: Char -> Bool
isAtomChar c = isAlphaNum c || c == '_' || c == '$'

tokenizeFormula :: String -> Either String [Token]
tokenizeFormula ('(' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (LeftParen : tokensTail)
tokenizeFormula (')' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (RightParen : tokensTail)
tokenizeFormula ('~' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (Operator "~" : tokensTail)
tokenizeFormula ('&' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (Operator "&" : tokensTail)
tokenizeFormula ('|' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (Operator "|" : tokensTail)
tokenizeFormula ('=' : '>' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (Operator "=>" : tokensTail)
tokenizeFormula ('<' : '=' : '>' : rest) = do
  tokensTail <- tokenizeFormula rest
  Right (Operator "<=>" : tokensTail)
tokenizeFormula formula@(x : rest)
  | isSpace x = tokenizeFormula rest
  | isAtomStart x = do
      tokensTail <- tokenizeFormula $ dropWhile isAtomChar formula
      Right (Atom (takeWhile isAtomChar formula) : tokensTail)
  | otherwise = Left $ "Unknown formula part " ++ (show x)
tokenizeFormula "" = Right []

statusLine :: String -> Maybe Status
statusLine fileLine =
  if "% Status (intuit.)" `isPrefixOf` fileLine
    then case dropWhile isSpace (drop 1 (dropWhile (/= ':') fileLine)) of
      "Theorem" -> Just Theorem
      "Non-Theorem" -> Just NonTheorem
      "Unsolved" -> Just Unsolved
      _ -> Nothing
    else Nothing

extractStatus :: String -> Either String Status
extractStatus fileContent =
  case mapMaybe statusLine (lines fileContent) of
    [] -> Left "Wrong file format : There is no Status line"
    (first : _) -> Right first

extractFof :: String -> Either String (String, String, String)
extractFof fof =
  case stripPrefix "fof(" (trim fof) of
    Nothing -> Left "Wrong file format : There is no fof prefix"
    Just content -> do
      (name, afterName) <- splitComma content
      (role, afterRole) <- splitComma afterName
      case stripSuffix ")." (trim afterRole) of
        Nothing -> Left "Wrong file format : There is no trailing )."
        Just formula -> Right (trim name, trim role, trim formula)
  where
    splitComma content =
      case findIndex (',' ==) content of
        Nothing -> Left "There is no ,"
        Just index -> Right (take index content, drop (index + 1) content)

extractFofs :: String -> Either String [(String, String)]
extractFofs "" = Right []
extractFofs content =
  let normalizeContent = trim content
   in if "fof" `isPrefixOf` normalizeContent
        then case findIndex ('.' ==) normalizeContent of
          Nothing -> Left "Wrong file format : There is no trailing ."
          Just dotPos -> do
            let fof = take (dotPos + 1) normalizeContent
            (_, role, formula) <- extractFof fof
            rest <- extractFofs $ drop (dotPos + 1) normalizeContent
            Right ((role, formula) : rest)
        else extractFofs $ drop 1 normalizeContent

normalizeFormulaText :: String -> String
normalizeFormulaText = unwords . words

extractProblem :: String -> Either String Problem
extractProblem problemSrc = do
  problemStatus <- extractStatus problemSrc
  fofs <- extractFofs problemSrc
  let axioms = map (normalizeFormulaText . snd) (filter (\(role, _) -> role == "axiom") fofs)
  let conjectures = filter (\(role, _) -> role == "conjecture") fofs
  case conjectures of
    [] -> Left "There is no conjecture in problem"
    [problem] -> Right $ Problem {status = problemStatus, hypotheses = axioms, conjecture = normalizeFormulaText $ snd problem}
    _ -> Left "There are more than one conjecture in problem"

data Arguments = Arguments
  { input :: FilePath,
    output :: FilePath, 
    clean :: Bool
  }
  deriving (Show)

defaultArguments :: Arguments
defaultArguments = Arguments {input = ".cache/iltp/ILTP-v1.1.2-propositional", output = "test/corpus/iltp", clean = False}

processArgs :: [String] -> StateT Arguments (Either String) ()
processArgs args = do
  case args of
    ("--input" : inputPath : rest) -> do
      modify (\ctx -> ctx {input = inputPath})
      processArgs rest
    ("--input" : _) -> lift (Left $ "--input requires argument")
    ("--output" : outputPath : rest) -> do
      modify (\ctx -> ctx {output = outputPath})
      processArgs rest
    ("--output" : _) -> lift (Left $ "--output requires argument")
    ("--clean" : rest) -> do 
        modify (\ctx -> ctx {clean = True})
        processArgs rest
    [] -> pure ()
    (arg : _) -> lift (Left $ "Unknown argument " ++ arg)

convertFile :: FilePath -> FilePath -> IO Bool
convertFile outputPrefix file = do
  fileContent <- readFile file
  let maybeProblem = extractProblem fileContent
  case maybeProblem of
    Left err -> die $ "Catch error during formulas extracting : " ++ err
    Right problem -> do
      let maybeParsedProblem = parseProblem problem
      case maybeParsedProblem of
        Left err -> die $ "Catch error during formula parsing : " ++ err
        Right parsedProblem -> do
          let maybeConvertedProblem = renderProblem parsedProblem
          case maybeConvertedProblem of
            Nothing -> pure False
            Just convertedProblem -> do
              let outputFileName = (map (\c -> if c == '.' then pathSeparator else c) (formatCaseId file)) ++ ".yaml"
              let outputFile = renderYaml file ("ipl.iltp." ++ (formatCaseId file)) convertedProblem
              createDirectoryIfMissing True outputPrefix
              createDirectoryIfMissing True (takeDirectory $ outputPrefix </> outputFileName)
              writeFile (outputPrefix </> outputFileName) outputFile
              pure True

collectProblems :: FilePath -> IO [FilePath]
collectProblems path = do
  files <- listDirectory path
  let paths = map (path </>) files
  let problems = filter (\name -> isSuffixOf ".p" name) paths
  subDirectories <- filterM (doesDirectoryExist) paths
  subProblems <- mapM collectProblems subDirectories
  pure $ sort $ problems ++ (concat subProblems)

main :: IO ()
main = do
  args <- getArgs
  case runStateT (processArgs args) defaultArguments of
    Left err ->
      die err
    Right (_, context) -> do
      isOutputExist <- doesPathExist (output context)   
      when (clean context && isOutputExist) $
        removeDirectoryRecursive (output context)  
      let problemsPath = (input context) </> "Problems"
      exists <- doesDirectoryExist problemsPath
      unless exists $ do
        die ("problems path " ++ problemsPath ++ " isn't exists ")
      problems <- collectProblems problemsPath
      results <- mapM (\file -> convertFile (output context) file) (problems)
      let converted = length $ filter id results
      let skipped = (length results) - converted
      putStrLn $ "converted: " ++ (show converted)
      putStrLn $ "skipped: " ++ (show skipped)

yamlQuote :: String -> String
yamlQuote str = "\"" ++ str ++ "\""

trim :: String -> String
trim = dropWhile isSpace . reverse . dropWhile isSpace . reverse

stripSuffix :: String -> String -> Maybe String
stripSuffix suffix text =
  if suffix `isSuffixOf` text
    then Just (take (length text - length suffix) text)
    else Nothing